// Infinite loops 


// this is a normal loops
for (let i = 1; i <= 20; i++) {
    console.log(i);
}

// this is a normal loops
for (let i = 20; i >= 1; i--) {
    console.log(i);
}

// this is a normal loops
for (let i = 5; i !== 10; i++) {
    console.log(i);
}


// this is an infinite loops 
for (let i = 1; i <= 20; i--) {
    console.log(i);
}

for (let i = 20; i >= 1; i++) {
    console.log(i);
}

for (let i = -20; i < 20; i -= 4) {
    console.log(i);
}